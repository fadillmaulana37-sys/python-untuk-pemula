angka_pertama = 10
angka_kedua = 5

hasil_tambah = angka_pertama + angka_kedua
hasil_kurang = angka_pertama - angka_kedua
hasil_kali = angka_pertama * angka_kedua
hasil_bagi = angka_pertama / angka_kedua

print("Angka pertama:", angka_pertama)
print("Angka kedua:", angka_kedua)
print("Hasil tambah:", hasil_tambah)
print("Hasil kurang:", hasil_kurang)
print("Hasil kali:", hasil_kali)
print("Hasil bagi:", hasil_bagi)